//! 编译期把只读资产内嵌进二进制：
//!   assets/static/  → Web 前端（原生 HTML/JS/CSS，无构建链）
//!   assets/js/      → QuickJS 引擎运行时（music-sdk + 2 个 preload + polyfill）
//!
//! 只用标准库，不引入任何 build-dependency，保证 `cargo build --locked`
//! 在 aarch64-unknown-linux-musl 上无需额外下载 crate。
use std::{env, fs, path::Path};

fn collect(base: &Path, dir: &Path, out: &mut Vec<String>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("无法读取资产目录 {}: {}", dir.display(), e))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            collect(base, &p, out);
        } else {
            let rel = p.strip_prefix(base).unwrap().to_string_lossy().replace('\\', "/");
            assert!(!rel.contains('"') && !rel.contains('\\'), "资产路径含非法字符: {rel}");
            out.push(rel);
        }
    }
}

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let root = Path::new(&manifest).join("assets");
    let out_dir = Path::new(&env::var("OUT_DIR").unwrap()).join("embedded_assets.rs");

    println!("cargo:rerun-if-changed=assets");
    for sub in ["static", "js"] {
        assert!(root.join(sub).is_dir(), "缺少资产目录: assets/{sub}");
    }

    let mut web = Vec::new();
    collect(&root.join("static"), &root.join("static"), &mut web);
    let mut js = Vec::new();
    collect(&root.join("js"), &root.join("js"), &mut js);

    let mut code = String::from("// @generated by build.rs —— 请勿手工编辑\n");
    code.push_str("pub static WEB: &[(&str, &[u8])] = &[\n");
    for f in &web {
        code.push_str(&format!(
            "    (\"{f}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/static/{f}\"))),\n"
        ));
    }
    code.push_str("];\n\npub static JS: &[(&str, &str)] = &[\n");
    for f in &js {
        code.push_str(&format!(
            "    (\"{f}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/js/{f}\"))),\n"
        ));
    }
    code.push_str("];\n");

    fs::write(&out_dir, code).unwrap();
}
